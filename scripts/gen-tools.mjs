// Regenerates src/content/tools/registry.ts and loaders.ts from the files in
// src/content/tools/calculators and src/content/tools/reference.
// Run: node scripts/gen-tools.mjs
import { readdirSync, writeFileSync } from 'node:fs';

const dir = 'src/content/tools';
const list = (d) => readdirSync(`${dir}/${d}`).filter((f) => f.endsWith('.ts')).map((f) => f.slice(0, -3)).sort();
const calcs = list('calculators');
const refs = list('reference');
const id = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase()).replace(/^(\d)/, '_$1');

const head = '// Generated by scripts/gen-tools.mjs. Do not edit by hand.\n';
writeFileSync(
  `${dir}/registry.ts`,
  head +
    `import type { Calculator, ReferenceTool } from '../types';\n` +
    calcs.map((s) => `import ${id(s)} from './calculators/${s}';`).join('\n') + '\n' +
    refs.map((s) => `import ${id(s)} from './reference/${s}';`).join('\n') + '\n\n' +
    `export const calculators: Calculator[] = [${calcs.map(id).join(', ')}];\n` +
    `export const referenceTools: ReferenceTool[] = [${refs.map(id).join(', ')}];\n`,
);
writeFileSync(
  `${dir}/loaders.ts`,
  head +
    `import type { Calculator } from '../types';\n\n` +
    `/** Client-side lazy loaders so each calculator page only downloads its own compute code. */\n` +
    `export const calculatorLoaders: Record<string, () => Promise<{ default: Calculator }>> = {\n` +
    calcs.map((s) => `  '${s}': () => import('./calculators/${s}'),`).join('\n') +
    `\n};\n`,
);
console.log(`registry: ${calcs.length} calculators, ${refs.length} reference tools`);
